#!/usr/bin/env python3
"""
gen_test_screen_tables.py - write test_screen_tables.asm, the font expansion
tables that test_screen.asm uses to draw 8x8 characters on 2 bpp and 4 bpp
rows.

    python3 gen_test_screen_tables.py

A font byte f has pixel i in bit i (bit 0 on the left).  Pixel i of a 2 bpp
byte is bits 2i+1:2i, and of a 4 bpp byte bits 4i+3:4i.  Each table turns f
into a mask with all the bits of the lit pixels set:

    EXP2_LO + f    pixels 0-3 of f as one 2 bpp byte
    EXP2_HI + f    pixels 4-7
    EXP4_0 + f     pixels 0-1 as one 4 bpp byte
    EXP4_1 + f     pixels 2-3
    EXP4_2 + f     pixels 4-5
    EXP4_3 + f     pixels 6-7

The program then makes a byte with (mask AND (fg XOR bg)) XOR bg.

Date: 10/17/2026
"""

import os


def exp(f, first, n, bpp):
    v = 0
    for i in range(n):
        if (f >> (first + i)) & 1:
            v |= ((1 << bpp) - 1) << (i * bpp)
    return v


TABLES = [
    ('EXP2_LO', lambda f: exp(f, 0, 4, 2)),
    ('EXP2_HI', lambda f: exp(f, 4, 4, 2)),
    ('EXP4_0', lambda f: exp(f, 0, 2, 4)),
    ('EXP4_1', lambda f: exp(f, 2, 2, 4)),
    ('EXP4_2', lambda f: exp(f, 4, 2, 4)),
    ('EXP4_3', lambda f: exp(f, 6, 2, 4)),
]


def main():
    out = ['; test_screen_tables.asm - generated by gen_test_screen_tables.py, do not edit',
           '; Font expansion tables for test_screen.asm: one page each, indexed by the',
           '; font byte.  See gen_test_screen_tables.py.',
           ';',
           '; Date: 10/17/2026',
           '']
    for name, fn in TABLES:
        out.append('#addr %s' % name)
        for row in range(16):
            vals = ', '.join('0x%02X' % fn(row * 16 + i) for i in range(16))
            out.append('    #d8 ' + vals)
        out.append('')
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'test_screen_tables.asm')
    open(path, 'w', newline='\n').write('\n'.join(out))
    print('wrote', path)


if __name__ == '__main__':
    main()
