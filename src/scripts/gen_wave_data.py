#!/usr/bin/env python3
"""
gen_wave_data.py - the sound player's font and pointer (wave_data.asm)

    python3 gen_wave_data.py

WAVE.PLC (wave.masm) draws its own card on a board, in Pinboard's look:
this writes Pinboard's font (gen_pinboard.py: the standard characters, a
card's edges, the pin, every one again in inverse video from x80) and its
pointer's two tables as the data wave.masm includes, at the addresses it
reads them from.

Date: 11/22/2026
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_pinboard    # noqa: E402

FONT = 0x3000           # 8 pages: page k = row k of every character
PTR = 0x3800            # 2 pages: the pointer's mask, its white pixels


def page(out, data):
    for i in range(0, 256, 16):
        out.append('    #d8 ' + ', '.join('0x%02X' % b for b in data[i:i + 16]))


def text():
    out = ['; wave_data.asm - generated by gen_wave_data.py, do not edit by hand',
           '; The sound player\'s font (Pinboard\'s: 8 pages, a page a row of every',
           '; character) and its pointer (the mask, the white pixels).',
           ';',
           '; Date: 11/22/2026',
           '',
           '#addr 0x%04X' % FONT]
    for rows in gen_pinboard.font_rows():
        page(out, rows)
    out.append('#addr 0x%04X' % PTR)
    for table in gen_pinboard.pointer_tables():
        page(out, table)
    return '\n'.join(out) + '\n'


def main():
    open(os.path.join(HERE, 'wave_data.asm'), 'w').write(text())
    print('wave_data.asm written')


if __name__ == '__main__':
    main()
