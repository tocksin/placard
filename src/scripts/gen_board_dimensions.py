#!/usr/bin/env python3
"""Main board dimension drawing (mm) -> docs/placard_main_dimensions.pdf.

    python3 src/scripts/gen_board_dimensions.py [--board kicad/placard.kicad_pcb]
                                                [--out docs/placard_main_dimensions.pdf]
                                                [--kicad-cli kicad-cli]

Needs KiCad 9 (its pcbnew Python module and kicad-cli): the board file is
KiCad 9 format. kicad/placard.kicad_pcb is never written. Each page is a
temporary copy of the board with the tracks and zones removed, everything
moved onto the middle of the C sheet, and KiCad dimension objects added on
Dwgs.User. kicad-cli plots Edge.Cuts, F.Fab (gray, for context) and
Dwgs.User; the pages are merged into one PDF that opens without the
bookmarks panel.

Page 1: board outline and mounting holes. Page 2: edge connectors (panel
opening centers from the datum). Page 3: expansion card and cartridge space
(the slot footprints' courtyards, which are the card shell keepouts).
All positions are read from the board, so rerun after the layout changes.
"""
import argparse
import datetime
import json
import os
import shutil
import subprocess
import sys
import tempfile

import pcbnew

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Board moved by this much on the sheet copy so the dimensions fit on C size.
DX, DY = 60.0, 45.0
TEXT = 2.5          # dimension text height
LINE = 0.18         # dimension and drawing line width
LAYER = pcbnew.Dwgs_User

SLOTS = [("J9", "Slot 1"), ("J10", "Slot 2"), ("J11", "Slot 3"), ("J12", "Slot 4")]

# Edge connectors: (ref, name, edge). Center/opening from the footprint's
# Dwgs.User panel line when it has one, else from its F.Fab body.
EDGE_PARTS = [
    ("J13", "USB-C power", "back"),
    ("J6", "Audio line out", "back"),
    ("J7", "VGA", "back"),
    ("J5", "PS/2 (2 ports)", "back"),
    ("SW1", "Power switch", "left"),
    ("SW2", "Reset button", "left"),
    ("J4", "SD card", "left"),
    ("J2", "SNES pad 1", "front"),
    ("J3", "SNES pad 2", "front"),
]


def mm(v):
    return pcbnew.FromMM(v)


def pt(x, y):
    """Board coordinates (as in the real board file) -> sheet copy."""
    return pcbnew.VECTOR2I(mm(x + DX), mm(y + DY))


def fmt(v):
    s = "%.2f" % v
    return s.rstrip("0").rstrip(".")


# ---------------------------------------------------------------- reading
def bbox(items):
    xs, ys = [], []
    for it in items:
        b = it.GetBoundingBox()
        w = pcbnew.ToMM(it.GetWidth()) / 2 if hasattr(it, "GetWidth") else 0.0
        xs += [pcbnew.ToMM(b.GetLeft()) + w, pcbnew.ToMM(b.GetRight()) - w]
        ys += [pcbnew.ToMM(b.GetTop()) + w, pcbnew.ToMM(b.GetBottom()) - w]
    return (min(xs), min(ys), max(xs), max(ys)) if xs else None


def fp_layer_box(fp, layer):
    return bbox([g for g in fp.GraphicalItems() if g.GetLayer() == layer])


def read_board(path):
    b = pcbnew.LoadBoard(path)
    edge = bbox([d for d in b.GetDrawings() if d.GetLayer() == pcbnew.Edge_Cuts])
    radius = None
    for d in b.GetDrawings():
        if d.GetLayer() == pcbnew.Edge_Cuts and d.GetShape() == pcbnew.SHAPE_T_ARC:
            radius = pcbnew.ToMM(d.GetRadius())
            break
    fps = {fp.GetReference(): fp for fp in b.GetFootprints()}
    holes = []
    for ref, fp in sorted(fps.items()):
        if ref.startswith("H"):
            big = max(fp.Pads(), key=lambda p: p.GetSizeX())
            c = big.GetPosition()
            holes.append((ref, pcbnew.ToMM(c.x), pcbnew.ToMM(c.y),
                          pcbnew.ToMM(big.GetDrillSizeX()), pcbnew.ToMM(big.GetSizeX())))
    return b, edge, radius, fps, holes


# ---------------------------------------------------------------- drawing
class Page:
    def __init__(self, src, title, edge):
        self.board = pcbnew.LoadBoard(src)
        b = self.board
        for t in list(b.GetTracks()):
            b.Delete(t)
        for z in list(b.Zones()):
            b.Delete(z)
        for d in list(b.GetDrawings()):
            # old notes on the user layers are not part of this drawing
            if d.GetLayer() in (pcbnew.Dwgs_User, pcbnew.Cmts_User):
                b.Delete(d)
        off = pcbnew.VECTOR2I(mm(DX), mm(DY))
        for fp in b.GetFootprints():
            fp.Move(off)
        for d in b.GetDrawings():
            d.Move(off)
        tb = b.GetTitleBlock()
        tb.SetTitle("Placard main board: dimensions")
        tb.SetComment(1, title)
        tb.SetComment(2, "All dimensions in mm. Datum: back left corner of the board outline.")
        tb.SetComment(3, "Generated by src/scripts/gen_board_dimensions.py from kicad/placard.kicad_pcb")
        tb.SetDate(datetime.date.today().isoformat())
        self.edge = edge

    def _style(self, d, text=TEXT):
        d.SetLayer(LAYER)
        d.SetUnitsMode(pcbnew.DIM_UNITS_MODE_MM)
        d.SetUnitsFormat(pcbnew.DIM_UNITS_FORMAT_NO_SUFFIX)
        d.SetPrecision(pcbnew.DIM_PRECISION_X_XX)
        d.SetSuppressZeroes(True)
        d.SetLineThickness(mm(LINE))
        d.SetTextSize(pcbnew.VECTOR2I(mm(text), mm(text)))
        d.SetTextThickness(mm(text * 0.12))
        d.SetArrowLength(mm(1.8))
        d.SetExtensionOffset(mm(0.5))
        d.SetKeepTextAligned(True)

    def horiz(self, x1, y1, x2, y2, at, prefix=""):
        """Horizontal distance x1->x2, dimension line at y = at."""
        d = pcbnew.PCB_DIM_ORTHOGONAL(self.board)
        self._style(d)
        d.SetOrientation(pcbnew.PCB_DIM_ORTHOGONAL.DIR_HORIZONTAL)
        d.SetStart(pt(x1, y1))
        d.SetEnd(pt(x2, y2))
        d.SetHeight(mm(at - y1))
        d.SetPrefix(prefix)
        self.board.Add(d)
        d.Update()
        return d

    def vert(self, x1, y1, x2, y2, at, prefix=""):
        """Vertical distance y1->y2, dimension line at x = at."""
        d = pcbnew.PCB_DIM_ORTHOGONAL(self.board)
        self._style(d)
        d.SetOrientation(pcbnew.PCB_DIM_ORTHOGONAL.DIR_VERTICAL)
        d.SetStart(pt(x1, y1))
        d.SetEnd(pt(x2, y2))
        d.SetHeight(mm(at - x1))
        d.SetPrefix(prefix)
        self.board.Add(d)
        d.Update()
        return d

    def center(self, cx, cy, r):
        d = pcbnew.PCB_DIM_CENTER(self.board)
        self._style(d)
        d.SetStart(pt(cx, cy))
        d.SetEnd(pt(cx + r, cy))
        self.board.Add(d)
        d.Update()

    def leader(self, x1, y1, x2, y2, text):
        d = pcbnew.PCB_DIM_LEADER(self.board)
        self._style(d)
        d.SetStart(pt(x1, y1))
        d.SetEnd(pt(x2, y2))
        d.SetOverrideTextEnabled(True)
        d.SetOverrideText(text)
        self.board.Add(d)
        d.Update()
        d.SetTextPos(pt(x2, y2))
        d.Update()

    def text(self, x, y, s, size=TEXT, left=True, angle=0, bold=False):
        t = pcbnew.PCB_TEXT(self.board)
        t.SetText(s)
        t.SetLayer(LAYER)
        t.SetPosition(pt(x, y))
        t.SetTextSize(pcbnew.VECTOR2I(mm(size), mm(size)))
        t.SetTextThickness(mm(size * (0.18 if bold else 0.12)))
        t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT if left else pcbnew.GR_TEXT_H_ALIGN_CENTER)
        t.SetVertJustify(pcbnew.GR_TEXT_V_ALIGN_TOP if left else pcbnew.GR_TEXT_V_ALIGN_CENTER)
        t.SetTextAngle(pcbnew.EDA_ANGLE(angle, pcbnew.DEGREES_T))
        self.board.Add(t)

    def shape(self, kind, a, b, width=LINE):
        s = pcbnew.PCB_SHAPE(self.board)
        s.SetShape(kind)
        s.SetLayer(LAYER)
        s.SetWidth(mm(width))
        s.SetStart(pt(*a))
        s.SetEnd(pt(*b))
        self.board.Add(s)
        return s

    def rect(self, x1, y1, x2, y2, width=LINE):
        return self.shape(pcbnew.SHAPE_T_RECT, (x1, y1), (x2, y2), width)

    def line(self, x1, y1, x2, y2, width=LINE):
        return self.shape(pcbnew.SHAPE_T_SEGMENT, (x1, y1), (x2, y2), width)

    def circle(self, cx, cy, r, width=LINE):
        return self.shape(pcbnew.SHAPE_T_CIRCLE, (cx, cy), (cx + r, cy), width)

    def edge_labels(self):
        l, t, r, b = self.edge
        self.text((l + r) / 2, t - 47, "BACK", size=4, left=False, bold=True)
        self.text((l + r) / 2, b + 47, "FRONT", size=4, left=False, bold=True)
        self.text(l - 55, (t + b) / 2, "LEFT", size=4, left=False, angle=90, bold=True)
        self.text(r + 55, (t + b) / 2, "RIGHT", size=4, left=False, angle=-90, bold=True)

    def overall(self):
        l, t, r, b = self.edge
        self.circle(l, t, 1.5)
        self.line(l - 3, t, l + 3, t)
        self.line(l, t - 3, l, t + 3)
        self.text(l - 4, t - 4, "DATUM (0, 0)", size=2.5, left=False)
        self.horiz(l, t, r, t, t - 38)
        self.vert(l, t, l, b, l - 38)

    def save(self, path):
        self.board.Save(path)


# ---------------------------------------------------------------- pages
def page_outline(src, edge, radius, holes):
    p = Page(src, "Sheet 1 of 3: board outline and mounting holes", edge)
    l, t, r, b = edge
    p.edge_labels()
    p.overall()
    # corner radius on the front left corner
    k = radius / 2 ** 0.5
    p.leader(l + radius - k, b - radius + k, l - 22, b + 22, "R%s, 4 corners" % fmt(radius))
    # holes: drill circle, pad circle, center mark
    for ref, x, y, drill, pad in holes:
        p.circle(x, y, drill / 2)
        p.circle(x, y, pad / 2, width=0.1)
        p.center(x, y, pad / 2 + 1.5)
        p.text(x + 4.5, y + 3.2, ref, size=2)
    # baseline dimensions from the datum (back left corner)
    xs = sorted({round(x, 3) for _, x, _, _, _ in holes})
    ys = sorted({round(y, 3) for _, _, y, _, _ in holes})
    for i, x in enumerate(xs):
        p.horiz(l, b, x, b, b + 12 + 8 * i)
    for i, y in enumerate(ys):
        p.vert(r, t, r, y, r + 12 + 8 * i)
    # hole spacing chain along the back edge
    for x1, x2 in zip(xs, xs[1:]):
        p.horiz(x1, ys[0], x2, ys[0], t - 16)
    for y1, y2 in zip(ys, ys[1:]):
        p.vert(xs[0], y1, xs[0], y2, l - 16)
    ref, x, y, drill, pad = max(holes, key=lambda h: (h[1], h[2]))
    p.leader(x + drill / 2 * 0.7, y + drill / 2 * 0.7, r + 12, b + 22,
             "%dx plated hole %s drill, %s pad (M3)" % (len(holes), fmt(drill), fmt(pad)))
    p.text(l, b + 52, "Board %s x %s mm, 1.6 mm thick, 4 layers, corner radius %s mm. "
           "Mounting holes %s mm from the edges." % (fmt(r - l), fmt(b - t), fmt(radius),
                                                     fmt(min(xs) - l)), size=3)
    return p


def edge_feature(fp, edge_name):
    """(center along the edge, opening width, overhang past the edge, box)."""
    panel = fp_layer_box(fp, pcbnew.Dwgs_User)
    fab = fp_layer_box(fp, pcbnew.F_Fab)
    box = panel if panel else fab
    if fp.GetReference() == "J7":       # VGA: center between the screw holes
        mh = [pd for pd in fp.Pads() if pd.GetDrillSizeX() > pcbnew.FromMM(2.5)]
        cx = sum(pcbnew.ToMM(pd.GetPosition().x) for pd in mh) / len(mh)
        box = (2 * cx - fab[2], fab[1], fab[2], fab[3])
    if edge_name in ("back", "front"):
        c, w = (box[0] + box[2]) / 2, box[2] - box[0]
    else:
        c, w = (box[1] + box[3]) / 2, box[3] - box[1]
    return c, w, fab


def page_edges(src, edge, fps):
    p = Page(src, "Sheet 2 of 3: edge connectors and controls (panel opening centers)", edge)
    l, t, r, b = edge
    p.edge_labels()
    p.overall()
    rows = []
    counts = {"back": 0, "left": 0, "front": 0}
    for ref, name, side in EDGE_PARTS:
        if ref not in fps:
            continue
        c, w, fab = edge_feature(fps[ref], side)
        n = counts[side]
        counts[side] += 1
        if side == "back":
            over = t - fab[1]
            p.horiz(l, t, c, t, t - 12 - 7 * n)
            p.line(c, t - 2, c, t + 8, width=0.1)
            dist = c - l
        elif side == "front":
            over = fab[3] - b
            p.horiz(l, b, c, b, b + 12 + 7 * n)
            p.line(c, b + 2, c, b - 8, width=0.1)
            dist = c - l
        else:
            over = l - fab[0]
            p.vert(l, t, l, c, l - 16 - 7 * n)
            p.line(l - 2, c, l + 8, c, width=0.1)
            dist = c - t
        p.text(fab[0] + 1, fab[1] + 1, ref, size=2)
        rows.append((ref, name, side, dist, w, max(over, 0.0)))
    # table to the right of the board
    x0, y0 = r + 18, t + 15
    cols = [0, 12, 44, 58, 76, 96]
    head = ["Ref", "Part", "Edge", "Center", "Opening", "Overhang"]
    for cx, h in zip(cols, head):
        p.text(x0 + cx, y0, h, size=2.5, bold=True)
    for i, (ref, name, side, dist, w, over) in enumerate(rows):
        y = y0 + 6 + 5 * i
        for cx, s in zip(cols, [ref, name, side, fmt(dist), fmt(w), fmt(over)]):
            p.text(x0 + cx, y, s, size=2.5)
    y = b + 52
    for s in ["Center: from the datum along that edge (back and front edges: from the left edge; "
              "left edge: from the back edge).",
              "Opening: panel cut-out width from the footprint's drawing layer, else the body width "
              "(VGA: shell width about the screw holes).",
              "Overhang: how far the body sticks out past the board edge."]:
        p.text(l, y, s, size=3)
        y += 5
    return p


def page_cards(src, edge, fps):
    p = Page(src, "Sheet 3 of 3: expansion card and cartridge space", edge)
    l, t, r, b = edge
    p.edge_labels()
    p.overall()
    boxes = []
    for ref, name in SLOTS:
        fp = fps.get(ref)
        if fp is None:
            continue
        k = fp_layer_box(fp, pcbnew.F_CrtYd)
        fab = fp_layer_box(fp, pcbnew.F_Fab)
        boxes.append((ref, name, k, fab))
        p.rect(*k, width=0.35)
        p.text((fab[2] + k[2]) / 2, (fab[1] + fab[3]) / 2 + 20, "%s (%s)" % (name, ref), size=3,
               left=False, angle=90)
    if boxes:
        # card space size on slot 1, pitch chain, first slot from the datum
        ref, name, k, fab = boxes[0]
        cxs = [(bx[3][0] + bx[3][2]) / 2 for bx in boxes]
        p.horiz(k[0], k[3], k[2], k[3], k[3] + 6)
        last = boxes[-1][2]
        p.vert(last[2], last[1], last[2], last[3], last[2] + 7)
        for c1, c2 in zip(cxs, cxs[1:]):
            p.horiz(c1, t, c2, t, t - 12)
        for bx, c in zip(boxes, cxs):
            p.line(c, bx[2][1] - 3, c, bx[2][3] + 3, width=0.1)
        p.horiz(l, t, cxs[0], t, t - 20)
        p.horiz(l, k[3], k[0], k[3], k[3] + 13)
        p.vert(l, t, l, k[3], l - 16)
        p.vert(l, t, l, (fab[1] + fab[3]) / 2, l - 24)
        ry = (fab[1] + fab[3]) / 2
        p.line(k[0] - 3, ry, boxes[-1][2][2] + 3, ry, width=0.1)
    fp = fps.get("J8")
    if fp is not None:
        k = fp_layer_box(fp, pcbnew.F_CrtYd)
        fab = fp_layer_box(fp, pcbnew.F_Fab)
        cx, cy = (fab[0] + fab[2]) / 2, (fab[1] + fab[3]) / 2
        p.rect(*k, width=0.35)
        p.text(cx, (fab[3] + k[3]) / 2 + 1, "Cartridge (J8)", size=3, left=False)
        p.line(cx, k[1] - 3, cx, k[3] + 3, width=0.1)
        p.line(k[0] - 3, cy, k[2] + 3, cy, width=0.1)
        p.horiz(k[0], k[1], k[2], k[1], k[1] - 7)
        p.vert(k[2], k[1], k[2], k[3], k[2] + 7)
        p.horiz(l, k[3], k[0], k[3], k[3] + 8)
        p.horiz(l, k[3], cx, k[3], k[3] + 15)
        p.vert(r, t, r, k[1], r + 14)
        p.vert(r, t, r, cy, r + 22)
    p.text(l, b + 52, "Boxes: space each card or cartridge shell takes at the board, plus 1 mm "
           "(the slot footprints' courtyards). Thin lines: connector center lines.", size=3)
    p.text(l, b + 57, "Cards and the cartridge stand up from the board; expansion cards run "
           "front to back and may carry a back-panel connector past the back edge.", size=3)
    return p


# ---------------------------------------------------------------- plotting
THEME = {
    "meta": {"name": "placard_dimensions", "version": 5},
    "board": {
        "background": "rgb(255, 255, 255)",
        "edge_cuts": "rgb(0, 0, 0)",
        "dwgs_user": "rgb(0, 0, 0)",
        "f_fab": "rgb(175, 175, 175)",
        "worksheet": "rgb(0, 0, 0)",
    },
}


def plot(cli, pcb, pdf, cfg):
    env = dict(os.environ, KICAD_CONFIG_HOME=cfg)
    subprocess.run([cli, "pcb", "export", "pdf", "-o", pdf,
                    "--layers", "F.Fab,Edge.Cuts,Dwgs.User",
                    "--include-border-title", "--theme", "placard_dimensions", pcb],
                   check=True, env=env)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", default=os.path.join(ROOT, "kicad", "placard.kicad_pcb"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "placard_main_dimensions.pdf"))
    ap.add_argument("--kicad-cli", default="kicad-cli")
    ap.add_argument("--keep", help="also save the page boards in this folder")
    a = ap.parse_args()

    _, edge, radius, fps, holes = read_board(a.board)
    tmp = tempfile.mkdtemp(prefix="placard_dim_")
    cfg = os.path.join(tmp, "config")
    major = pcbnew.Version().split(".")[0] + ".0"
    for d in (cfg, os.path.join(cfg, major)):
        os.makedirs(os.path.join(d, "colors"), exist_ok=True)
        with open(os.path.join(d, "colors", "placard_dimensions.json"), "w") as f:
            json.dump(THEME, f)
    pages = [page_outline(a.board, edge, radius, holes),
             page_edges(a.board, edge, fps),
             page_cards(a.board, edge, fps)]
    pdfs = []
    for i, p in enumerate(pages, 1):
        pcb = os.path.join(tmp, "page%d.kicad_pcb" % i)
        p.save(pcb)
        if a.keep:
            os.makedirs(a.keep, exist_ok=True)
            shutil.copy(pcb, a.keep)
        pdf = os.path.join(tmp, "page%d.pdf" % i)
        plot(a.kicad_cli, pcb, pdf, cfg)
        pdfs.append(pdf)

    import pypdf
    w = pypdf.PdfWriter()
    for pdf in pdfs:
        w.append(pdf, import_outline=False)
    if "/Outlines" in w._root_object:
        del w._root_object["/Outlines"]
    w.page_mode = "/UseNone"
    with open(a.out, "wb") as f:
        w.write(f)
    shutil.rmtree(tmp, ignore_errors=True)
    print("wrote", a.out)


if __name__ == "__main__":
    sys.exit(main())
