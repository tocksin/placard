#!/usr/bin/env python3
"""
gen_lib_sqtab.py - writes lib_sqtab.asm, the quarter-square tables mul8 uses

    python3 gen_lib_sqtab.py

a * b = f(a + b) - f(|a - b|) with f(n) = n * n // 4 (exact for whole
numbers), so a multiply is two table look-ups and a subtract.  The tables
hold f(n) for n = 0-255: the low bytes at SQ_LO (xFF00) and the high bytes
at SQ_HI (xFC00).  xFC00 itself is the boot mode byte, so SQ_HI has no
entry 0 (mul8 never reads it: f(0) = 0).  mul8 works out f(256 + k), for
a + b over 255, as f(k) + 128 k + 16384.

The tables are in the boot loader's pages, so rom_boot.asm includes this
file (every ROM image has it); placard_lib.asm only names the addresses.

Date: 11/11/2026
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rows(vals):
    return ['    #d8 ' + ', '.join('0x%02X' % v for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]


def main():
    f = [n * n // 4 for n in range(256)]
    L = ['; lib_sqtab.asm - generated by gen_lib_sqtab.py, do not edit by hand',
         '; Quarter squares for mul8 (placard_lib.asm): f(n) = n * n / 4, n = 0-255.',
         '; rom_boot.asm includes this file: the tables are in the boot loader\'s',
         '; free pages.  SQ_HI has no entry 0 (xFC00 is the boot mode byte).',
         ';',
         '; Date: 11/11/2026',
         '',
         '#addr 0xFC01                ; SQ_HI + 1: the high bytes of f(1) - f(255)']
    L += rows([v >> 8 for v in f[1:]])
    L += ['#addr 0xFF00                ; SQ_LO: the low bytes of f(0) - f(255)']
    L += rows([v & 0xFF for v in f])
    with open(os.path.join(HERE, 'lib_sqtab.asm'), 'w', newline='\n') as fh:
        fh.write('\n'.join(L) + '\n')
    print('wrote lib_sqtab.asm')


if __name__ == '__main__':
    main()
