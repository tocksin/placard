def glyph(c):
    """8 rows of character code c (0-255)"""
    base = c & 0x7F
    rows = FONT[base - 0x20] if 0x20 <= base < 0x7F else (0,) * 8
    if c & 0x80:
        rows = tuple(r ^ 0xFF for r in rows)
    return rows


def main():
    out = ['; lib_font.asm - generated by gen_lib_font.py, do not edit by hand',
           '; 8x8 font for placard_lib.asm: page LIB_FONT + k holds row k of every',
           '; character, indexed by code.  80-FF are 00-7F in inverse video.',
           '; font8x8_basic by Daniel Hepper (public domain).',
           ';',
           '; Date: 10/16/2026',
           '']
    for k in range(8):
        out.append('#addr LIB_FONT + 0x%03X     ; row %d' % (k * 256, k))
        for c0 in range(0, 256, 16):
            out.append('    #d8 ' + ', '.join('0x%02X' % glyph(c)[k] for c in range(c0, c0 + 16)))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'lib_font.asm')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
